const v = (x) => (x === undefined || x === null ? '' : String(x).trim());
// profissão do caso: a escolhida no cadastro ou a reconhecida pelo cargo / funções
export function profissaoDoCaso(c = {}, periodos = []) {
  if (v(c.profissao)) return PROFISSOES.find((p) => p.id === c.profissao || p.nome === c.profissao) || null;
  const t = [c.funcoes, c.atividadesAlegadas, ...periodos.map((r) => `${(r.data || r).cargo || ''} ${(r.data || r).atividades || ''}`)].map(v).join(' ');
  return PROFISSOES.find((p) => p.re.test(t)) || null;
}

// referência da profissão para a instrução do Claude (critérios do signatário)
export function referenciaProfissao(p) {
  if (!p) return '';
  const res = (a, cod, r) => `${r || 'a confirmar'}${cod ? ` (cód. ${cod})` : ''}`;
  return [`REFERÊNCIA DA PROFISSÃO – ${p.nome.toUpperCase()} (critérios já adotados pelo signatário em laudos anteriores; use como ponto de partida e ajuste ao que o segurado informar)`,
    `- CBO: ${p.cbo} (${p.cboNome}). Profissiografia padrão: ${p.profissiografia}`,
    `- EPI: ${p.epi}`,
    '- Agentes avaliados ("agentesAvaliados"): inclua os que o segurado usa ou usou, com os campos do art. 68 (circunstancias, fonte, vias, frequencia), CAS e efeitos; mantenha os resultados abaixo, salvo informação concreta em contrário; agente que o segurado não usa fica de fora; uso a confirmar fica "A confirmar". Deixe "tecnica" vazio (o app preenche pelo Manual de Aposentadoria Especial do INSS).',
    ...p.agentes.map((a) => `  • [${a.tipo}] ${a.nome}: até 05/03/1997 ${res(a, a.codAte97, a.resAte97)}; a partir de 06/03/1997 ${res(a, a.codDesde97, a.resDesde97)}`),
    `- Roteiro de entrevista: ${p.roteiro.join(' ')}`,
    `- Documentos a pedir: ${p.documentos.join('; ')}.`].join('\n');
}
